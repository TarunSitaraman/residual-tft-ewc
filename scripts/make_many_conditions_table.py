"""Paper table of the many-condition tests on unseen usage conditions: D34 (S7, 60 test conditions) and D36 (S10,
64 test conditions), horizons 1-3 (E1) and 1-6 (E2).

Top: mean RMSE over held-out conditions (pp); main/replicate seed sets for the proposed model, main set for the
joint TFT, single values for the deterministic baselines. Bottom: the registered primary verdicts (D21 rule over
conditions), with the main-set difference (the replicate-set difference is checked to lie within 0.04 pp of it,
as the caption states). The proposed model is the registered one of each decision: shrunk everywhere (D34) and
shrunk only where extrapolation has a fade rate (D36). Writes paper/tables/many_conditions.tex.

    python scripts/make_many_conditions_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RUNS = (("S7", "d34", "tft_residual_ewc_shrunk"), ("S10", "d36", "tft_residual_ewc_selective"))
EXPS = ("e1", "e2")
SHORT = {"replicated, a better": "better", "replicated, a worse": "worse",
         "practically equivalent": "equiv.", "not replicated": "n.r."}
ROWS = (("\\textbf{Proposed}", "proposed"), ("Lin.\\ extrapolation", "linear_extrapolation"),
        ("GB, latest only", "gbm_last"), ("GB, all stored", "gbm_all"),
        ("Joint residual TFT", "tft_residual_joint"), ("Persistence", "persistence"))
TESTS = (("vs.\\ GB, latest only", "gbm_last", "rmse"),
         ("vs.\\ lin., H$^+$", "linear_extrapolation", "rmse_hplus"),
         ("vs.\\ GB, all stored", "gbm_all", "rmse"))
REP_GAP = 0.04          # stated in the caption


def load(dec: str, exp: str) -> dict:
    return json.loads((ROOT / "results" / f"forecasting_{dec}_{exp}.json").read_text())


def collect() -> dict:
    out = {}
    for ds, dec, prop in RUNS:
        for e in EXPS:
            d = load(dec, e)
            cv = pd.DataFrame(d["condition_values"])
            out[(ds, e)] = {
                "means": cv.pivot_table(index="method", columns="set", values="rmse"), "prop": prop,
                "tests": {(t["set"], t["b"], t["metric"]): t for t in d["tests"] if t["a"] == prop},
                "verdicts": {(v["b"], v["metric"]): v for v in d["verdicts"]
                             if v["a"] == prop and v["family"] == "primary"},
                "n": int(cv.loc[cv["method"] == prop, "condition"].nunique())}
    return out


def mean_cell(c: dict, method: str) -> str:
    m = c["means"].loc[c["prop"] if method == "proposed" else method]
    return f"{m['main']:.2f}/{m['replicate']:.2f}" if method == "proposed" else f"{m['main']:.2f}"


def test_cell(c: dict, b: str, metric: str) -> str:
    v = c["verdicts"][(b, metric)]
    tm = c["tests"][("main", b, metric)]
    txt = f"${v['diff_main']:+.2f}$ {SHORT[v['verdict']]}"
    # The registered rule takes the direction from the mean; flag a significant result whose ranks disagree.
    if v["verdict"].startswith("replicated") and (tm["median_diff"] > 0) != (v["diff_main"] > 0):
        txt += "$^\\ddagger$"
    return txt


def table(data: dict) -> str:
    cols = [(ds, e) for ds, _, _ in RUNS for e in EXPS]
    body = [f"    {lab} & " + " & ".join(mean_cell(data[k], m) for k in cols) + " \\\\" for lab, m in ROWS]
    tbody = [f"    {lab} & " + " & ".join(test_cell(data[k], b, m) for k in cols) + " \\\\" for lab, b, m in TESTS]
    n = {ds: data[(ds, "e1")]["n"] for ds, _, _ in RUNS}
    return "\n".join([
        "% Generated by scripts/make_many_conditions_table.py from results/forecasting_d34_e*.json and"
        " results/forecasting_d36_e*.json",
        "\\begin{table}[t]",
        "  \\centering",
        f"  \\caption{{Unseen usage conditions under the continual constraint: S7 ({n['S7']} test conditions) and S10",
        f"    ({n['S10']}). Top: mean test RMSE over conditions (pp); proposed: main/replicate seeds, shrunk on S7 at every",
        "    origin, on S10 at H$^+$ only; joint TFT: main set; GB: gradient boosting. Bottom: proposed minus baseline (pp,",
        f"    main set; replicate within {REP_GAP:.2f}~pp) and verdict (as Table~\\ref{{tab:headline}}). $^\\ddagger$Mean set by",
        "    a few calendar conditions; GB is better on 52 of 64.}",
        "  \\label{tab:many}",
        "  \\setlength{\\tabcolsep}{2pt}",
        "  \\scriptsize",
        "  \\begin{tabular}{lcccc}",
        "    \\toprule",
        "    & \\multicolumn{2}{c}{S7 (D34)} & \\multicolumn{2}{c}{S10 (D36)} \\\\",
        "    \\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
        "    & $h{=}1$--3 & $h{=}1$--6 & $h{=}1$--3 & $h{=}1$--6 \\\\",
        "    \\midrule",
        *body,
        "    \\midrule",
        *tbody,
        "    \\bottomrule",
        "  \\end{tabular}",
        "\\end{table}",
        "",
    ])


def main() -> int:
    data = collect()
    gaps = [abs(v["diff_main"] - v["diff_replicate"]) for c in data.values() for v in c["verdicts"].values()]
    assert max(gaps) <= REP_GAP + 5e-3, max(gaps)
    flagged = [k for k in data for _, b, m in TESTS if test_cell(data[k], b, m).endswith("$^\\ddagger$")]
    assert flagged == [("S10", "e1")], flagged      # the caption's footnote describes exactly this cell
    t = data[("S10", "e1")]["tests"][("main", "gbm_all", "rmse")]
    assert t["n_conditions_b_better"] == 52 and t["n"] == 64, t
    (ROOT / "paper" / "tables" / "many_conditions.tex").write_text(table(data), encoding="utf-8")
    print(table(data))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
