"""Comparison table and confusion figure of the reuse classes on unseen S6 conditions (D26 E1 set-up).

From results/forecasting_d26_classes_e1.json (scripts/run_d26_classes.py). Writes
paper/tables/d26_classes.tex (accuracy, sensitivity = macro recall, precision = macro precision, macro-F1, MCC) and
paper/figures/d26_confusion.png (mean counts over the 50 runs for the proposed model; single fits otherwise).

    python scripts/make_d26_class_outputs.py
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "results" / "forecasting_d26_classes_e1.json"
ROWS = (  # (key, label)
    ("persistence", "Persistence"),
    ("linear_extrapolation", "Linear extrapolation"),
    ("ridge_shared", "Ridge"),
    ("gbm_shared", "Gradient boosting"),
    ("tft_residual_ewc_shrunk", "\\textbf{Residual TFT-EWC} (proposed)"),
)
COLS = (("accuracy", "Acc."), ("recall_macro", "Sens."), ("precision_macro", "Prec."), ("f1_macro", "F1"),
        ("mcc", "MCC"))
FIG = (("linear_extrapolation", "Linear extrapolation"), ("gbm_shared", "Gradient boosting"),
       ("tft_residual_ewc_shrunk", "Residual TFT-EWC (mean)"))


def table(d: dict) -> str:
    s = d["summary"]
    best = {k: max(s[m][k]["mean"] for m, _ in ROWS) for k, _ in COLS}
    lines = []
    for key, label in ROWS:
        cells = []
        for k, _ in COLS:
            v = s[key][k]["mean"]
            cells.append(f"\\textbf{{{v:.3f}}}" if abs(v - best[k]) < 5e-4 else f"{v:.3f}")
        lines.append(f"    {label} & " + " & ".join(cells) + " \\\\")
        if key == "tft_residual_ewc_shrunk":
            sd = " & ".join(f"$\\pm${s[key][k]['std']:.3f}" for k, _ in COLS)
            lines.append(f"    \\quad s.d.\\ over 50 runs & {sd} \\\\")
    cm = np.array(s["linear_extrapolation"]["confusion_mean"])
    counts = ", ".join(f"C{i} {int(n)}" for i, n in enumerate(cm.sum(axis=1)))
    return "\n".join([
        f"% Generated by scripts/make_d26_class_outputs.py from {SRC.relative_to(ROOT).as_posix()}",
        "\\begin{table}[t]",
        "  \\centering",
        "  \\caption{Reuse class of the forecast SOH on unseen S6 conditions (P2, horizons 1--3, seven held-out",
        f"    conditions pooled; measured {counts}). Sens., Prec.: macro recall and precision. Proposed model: mean",
        "    and s.d.\\ over 50 runs; others: single fits. Bold: best.}",
        "  \\label{tab:d26_classes}",
        "  \\setlength{\\tabcolsep}{2.2pt}",
        "  \\scriptsize",
        "  \\begin{tabular}{lccccc}",
        "    \\toprule",
        "    Approach & " + " & ".join(h for _, h in COLS) + " \\\\",
        "    \\midrule",
        *lines,
        "    \\bottomrule",
        "  \\end{tabular}",
        "\\end{table}",
        "",
    ])


def figure(d: dict) -> None:
    s = d["summary"]
    fig, axes = plt.subplots(1, 3, figsize=(3.5, 1.45), sharey=True)
    for ax, (key, title) in zip(axes, FIG):
        cm = np.array(s[key]["confusion_mean"], float)
        share = cm / np.maximum(cm.sum(axis=1, keepdims=True), 1)
        ax.imshow(share, cmap="Blues", vmin=0, vmax=1)
        for i in range(cm.shape[0]):
            for j in range(cm.shape[1]):
                ax.text(j, i, f"{cm[i, j]:.0f}", ha="center", va="center", fontsize=5,
                        color="w" if share[i, j] > 0.6 else "k")
        ax.set_title(title, fontsize=5.8)
        ax.set_xticks(range(4), [f"C{i}" for i in range(4)], fontsize=5)
        ax.set_yticks(range(4), [f"C{i}" for i in range(4)], fontsize=5)
        ax.set_xlabel("forecast class", fontsize=5.5)
        ax.tick_params(length=1.5, pad=1)
    axes[0].set_ylabel("measured class", fontsize=5.5)
    fig.tight_layout(pad=0.2, w_pad=0.4)
    fig.savefig(ROOT / "paper" / "figures" / "d26_confusion.png", dpi=400)
    plt.close(fig)


def main() -> int:
    d = json.loads(SRC.read_text())
    (ROOT / "paper" / "tables" / "d26_classes.tex").write_text(table(d), encoding="utf-8")
    figure(d)
    print("wrote paper/tables/d26_classes.tex and paper/figures/d26_confusion.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
