"""Tables and figures for D30 (full regression and classification metric set) from committed results files.

Reads ``results/forecasting_d30_s1.json`` and ``results/forecasting_d30_s6.json`` (written by ``scripts/run_d30.py``;
a missing file is skipped with a message, a file written from a dirty tree or with the smoke profile is refused) and
writes, never edited by hand:

- ``results/tables/d30_regression.csv``, ``d30_classification.csv``, ``d30_per_group.csv``;
- ``paper/tables/d30_regression.tex``: P2, every regression metric, mean over held-out groups (as Table P2, so the
  RMSE column must equal Table P2 to the run's tolerances; checked here);
- ``paper/tables/d30_classification.tex``: P2, reuse-class and end-of-first-life (SOH <= 80) metrics on all held-out
  samples pooled (per-group classes are mostly a single class);
- ``paper/figures/d30_confusion.png``: pooled reuse-class confusion matrices (S6, four methods);
- ``paper/figures/d30_error_by_group.png``: MAE and bias per held-out group.

Usage (from the repository root)::

    python scripts/make_d30_outputs.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_d24_outputs as S  # noqa: E402  (Agg backend, shared rcParams, write_tex, fmt)

ROOT = S.ROOT
DATASETS = {"s1": "S1", "s6": "S6"}
COMMITTED = {"s1": ROOT / "results" / "forecasting.json", "s6": ROOT / "results" / "forecasting_wheeler.json"}
ORDER = ["persistence", "linear_extrapolation", "ridge_schedule", "ridge_F0", "ridge_F1", "gbm_F1", "mlp", "tft"]
NAMES = {"persistence": "Persistence", "linear_extrapolation": "Linear extrapolation", "ridge_schedule": "Ridge, usage only",
         "ridge_F0": "Ridge, F0", "ridge_F1": "Ridge, F1", "gbm_F1": "Gradient boosting, F1", "mlp": "MLP", "tft": "TFT"}
CLASS_NAMES = ("C0", "C1", "C2", "C3")
CONFUSION_METHODS = ("persistence", "linear_extrapolation", "gbm_F1", "tft")
GROUP_METHODS = (("linear_extrapolation", S.GREY), ("gbm_F1", "#1baf7a"), ("tft", S.FAMILY_COLOUR["tft"]))


def load() -> dict:
    res = {}
    for k in DATASETS:
        path = S.RES / f"forecasting_d30_{k}.json"
        if not path.exists():
            print(f"skip {k}: {path.relative_to(ROOT)} not found (run scripts/run_d30.py --dataset {k})")
            continue
        r = json.loads(path.read_text())
        if r["environment"].get("git_dirty") or r.get("profile") != "paper":
            raise SystemExit(f"{path} is not reportable (dirty tree or smoke profile); re-run on a clean commit")
        if not r["reproduction_check"].get("passed"):
            raise SystemExit(f"{path}: reproduction check did not pass")
        res[k] = r
    return res


def frame(r: dict, key: str) -> pd.DataFrame:
    d = pd.DataFrame(r[key])
    return d.set_index("method").reindex([m for m in ORDER if m in set(d["method"])])


def check_against_p2(k: str, over: pd.DataFrame, rep: dict) -> float:
    """The mean-over-groups RMSE must equal the committed Table P2 value (same averaging), to the run's tolerances.
    Returns the largest difference of a neural method (re-run; D30 run log)."""
    committed = {row["method"]: row["mean"] for row in json.loads(COMMITTED[k].read_text())["p2_rmse"]}
    neural = 0.0
    for m, v in over["reg_RMSE"].items():
        tol = rep["tolerance"] if m in ORDER[:6] else rep.get("neural_tolerance", rep["tolerance"])
        if abs(v - committed[m]) > tol:
            raise SystemExit(f"{k} {m}: D30 RMSE {v} differs from committed P2 RMSE {committed[m]}")
        if m not in ORDER[:6]:
            neural = max(neural, abs(v - committed[m]))
    return neural


def src_line(res: dict) -> str:
    return "% Generated by scripts/make_d30_outputs.py from " + ", ".join(
        f"results/forecasting_d30_{k}.json (commit {r['environment']['git_commit'][:7]})" for k, r in res.items()) + "\n"


REG_COLS = [("reg_RMSE", "RMSE"), ("reg_MSE", "MSE"), ("reg_MAE", "MAE"), ("reg_MedAE", "MedAE"), ("reg_Bias", "Bias"),
            ("reg_NRMSE", "NRMSE"), ("reg_MAPE", "MAPE (\\%)"), ("reg_R2", "$R^2$"), ("reg_R2_change", "$R^2_\\Delta$")]
CLS_COLS = [("cls_accuracy", "Acc."), ("cls_balanced_accuracy", "Bal. acc."), ("cls_precision_macro", "Prec."),
            ("cls_recall_macro", "Rec."), ("cls_specificity_macro", "Spec."), ("cls_f1_macro", "F1"),
            ("cls_mcc", "MCC"), ("cls_kappa", "$\\kappa$"), ("cls_kappa_linear", "$\\kappa_w$")]
EOL_COLS = [("eol_precision", "Prec."), ("eol_recall", "Rec."), ("eol_specificity", "Spec."), ("eol_f1", "F1"),
            ("eol_mcc", "MCC"), ("eol_auc_roc", "AUC")]


def regression(res: dict) -> pd.DataFrame:
    rows, body, neural = [], [], 0.0
    for k, r in res.items():
        over = frame(r, "p2_over_groups")
        neural = max(neural, check_against_p2(k, over, r["reproduction_check"]))
        for m, row in over.iterrows():
            rows.append({"dataset": DATASETS[k], "method": m, **{c: row[c] for c, _ in REG_COLS},
                         **{f"{c}_sd_over_groups": row[f"{c}_sd"] for c, _ in REG_COLS}})
            body.append([DATASETS[k], NAMES[m], *[S.fmt(row[c], 3) if c != "reg_Bias" else S.sfmt(row[c], 3)
                                                  for c, _ in REG_COLS]])
        body.append(None)
    S.write_tex(S.PTAB / "d30_regression.tex",
                "Protocol P2, all regression metrics of the forecast SOH (pp unless stated), mean over held-out groups "
                "(the RMSE column equals Table~\\ref{tab:p2} for the baselines; MLP and TFT are re-runs on another "
                f"platform, within {neural:.4f}~pp of it). Bias = mean(forecast $-$ measured): positive values "
                "overestimate SOH. NRMSE = RMSE / range of measured SOH in the group. $R^2$ is on the SOH level, "
                "$R^2_\\Delta$ on the SOH change since the origin (persistence has $R^2_\\Delta \\le 0$). SOH is relative "
                "to the first observed check.",
                "tab:d30_regression", ["Data", "Method", *[h for _, h in REG_COLS]],
                _with_rules(body), "ll" + "c" * len(REG_COLS), escape=False)
    _prepend(S.PTAB / "d30_regression.tex", src_line(res))
    return pd.DataFrame(rows)


def classification(res: dict) -> pd.DataFrame:
    rows, body = [], []
    for k, r in res.items():
        pooled = frame(r, "p2_pooled")
        for m, row in pooled.iterrows():
            rows.append({"dataset": DATASETS[k], "method": m, "n_samples": row["n_samples"],
                         **{c: row[c] for c, _ in CLS_COLS + EOL_COLS}})
            body.append([DATASETS[k], NAMES[m], *[S.fmt(row[c], 2) for c, _ in CLS_COLS + EOL_COLS]])
        body.append(None)
    support = {DATASETS[k]: np.sum(list(r["class_support"].values()), axis=0).tolist() for k, r in res.items()}
    note = "; ".join(f"{d}: " + ", ".join(f"{c} {n}" for c, n in zip(CLASS_NAMES, s)) for d, s in support.items())
    S.write_tex(S.PTAB / "d30_classification.tex",
                "Protocol P2, reuse class (C0--C3, D10 cut-points) and end-of-first-life decision (SOH $\\le$ 80, "
                "positive) of the forecast SOH against the measured SOH, all held-out samples pooled (mean over seeds). "
                "Macro averages run over the measured classes. AUC uses the forecast SOH as the score (point forecasts; "
                f"no class probabilities, so no log loss). Measured class counts of all samples: {note}. "
                "-- : undefined (one class only).",
                "tab:d30_classification",
                ["Data", "Method", *[h for _, h in CLS_COLS], *[f"EoL {h}" for _, h in EOL_COLS]],
                _with_rules(body), "ll" + "c" * (len(CLS_COLS) + len(EOL_COLS)), escape=False)
    _prepend(S.PTAB / "d30_classification.tex", src_line(res))
    if "s6" in res:
        compact_s6(res, support["S6"])
    return pd.DataFrame(rows)


COMPACT_COLS = [("cls_accuracy", "Acc."), ("cls_f1_macro", "F1"), ("cls_mcc", "MCC"), ("cls_kappa_linear", "$\\kappa_w$"),
                ("eol_f1", "EoL F1"), ("eol_auc_roc", "EoL AUC")]


def compact_s6(res: dict, support: list) -> None:
    """One-column S6 classification table for the main text (the full table stays in the repository)."""
    pooled = frame(res["s6"], "p2_pooled")
    body = [[NAMES[m], *[S.fmt(row[c], 3) for c, _ in COMPACT_COLS]] for m, row in pooled.iterrows()]
    counts = ", ".join(f"{c} {n}" for c, n in zip(CLASS_NAMES, support))
    S.write_tex(S.PTAB / "d30_classification_s6.tex",
                "S6, P2: reuse class (C0--C3) and end of first life (EoL, SOH $\\le$ 80) of the forecast SOH, all "
                "held-out samples pooled, mean over seeds. F1: macro over the measured classes; $\\kappa_w$: "
                f"linear-weighted. Measured classes: {counts}. All metrics in the repository (D30).",
                "tab:d30_cls_s6", ["Method", *[h for _, h in COMPACT_COLS]], body, "l" + "c" * len(COMPACT_COLS),
                escape=False)
    path = S.PTAB / "d30_classification_s6.tex"
    path.write_text(src_line({"s6": res["s6"]}) + path.read_text())


def _with_rules(body: list) -> list:
    """``None`` entries separate datasets; turn them into \\midrule rows (dropping the last)."""
    while body and body[-1] is None:
        body.pop()
    return [[r"\midrule"] if row is None else row for row in body]


def _prepend(path: Path, text: str) -> None:
    """Add the provenance line, turn separator rows into plain \\midrule and span both columns (wide tables)."""
    content = path.read_text().replace("    \\midrule \\\\\n", "    \\midrule\n")
    content = content.replace("\\begin{table}[t]", "\\begin{table*}[t]").replace("\\end{table}", "\\end{table*}")
    path.write_text(text + content)


def per_group(res: dict) -> pd.DataFrame:
    out = []
    for k, r in res.items():
        d = pd.DataFrame(r["p2_per_group"])
        out.append(d.assign(dataset=DATASETS[k]))
    return pd.concat(out, ignore_index=True)


def fig_confusion(res: dict) -> Path | None:
    if "s6" not in res:
        return None
    pooled = pd.DataFrame(res["s6"]["p2_pooled"]).set_index("method")
    methods = [m for m in CONFUSION_METHODS if m in pooled.index]
    fig, axes = plt.subplots(1, len(methods), figsize=(1.85 * len(methods), 2.6), sharey=True)
    for ax, m in zip(np.atleast_1d(axes), methods):
        cm = np.asarray(pooled.loc[m, "confusion"], float)
        norm = cm / np.where(cm.sum(axis=1, keepdims=True) > 0, cm.sum(axis=1, keepdims=True), 1)
        ax.imshow(norm, cmap="Blues", vmin=0, vmax=1)
        for (i, j), v in np.ndenumerate(cm):
            ax.text(j, i, f"{int(v)}", ha="center", va="center", fontsize=7,
                    color="white" if norm[i, j] > 0.6 else S.INK)
        ax.set_xticks(range(4), CLASS_NAMES)
        ax.set_yticks(range(4), CLASS_NAMES)
        ax.set_xlabel("Forecast class")
        ax.set_title(NAMES[m].replace(", F1", ""), fontsize=8, loc="left")
        ax.grid(False)
    np.atleast_1d(axes)[0].set_ylabel("Measured class")
    fig.suptitle("S6, P2: reuse-class confusion (counts; shading = row share), seed 0", fontsize=9, x=0.01, ha="left")
    fig.tight_layout()
    out = S.FIG / "d30_confusion.png"
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    return out


def fig_error_by_group(groups: pd.DataFrame) -> Path:
    ds = list(dict.fromkeys(groups["dataset"]))
    fig, axes = plt.subplots(2, len(ds), figsize=(3.6 * len(ds), 4.4), squeeze=False)
    width = 0.8 / len(GROUP_METHODS)
    for c, d in enumerate(ds):
        g = groups[groups["dataset"] == d]
        names = sorted(g["Battery_ID"].unique(), key=str)
        x = np.arange(len(names))
        for i, (m, colour) in enumerate(GROUP_METHODS):
            sub = g[g["method"] == m].set_index("Battery_ID").reindex(names)
            for r, (col, ylab) in enumerate((("reg_MAE", "MAE (pp)"), ("reg_Bias", "Bias (pp)"))):
                axes[r, c].bar(x + (i - (len(GROUP_METHODS) - 1) / 2) * width, sub[col], width, color=colour,
                               label=NAMES[m] if (r, c) == (0, 0) else None)
                axes[r, c].set_ylabel(ylab)
        for r in range(2):
            axes[r, c].set_xticks(x, names, fontsize=7)
            axes[r, c].grid(axis="x", visible=False)
        axes[1, c].axhline(0, color=S.INK, linewidth=0.8)
        axes[1, c].set_xlabel("Held-out group")
        axes[0, c].set_title(f"{d}, P2", loc="left")
    fig.legend(loc="lower center", ncol=len(GROUP_METHODS), fontsize=8, bbox_to_anchor=(0.5, -0.02))
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    out = S.FIG / "d30_error_by_group.png"
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    return out


def main() -> int:
    res = load()
    if not res:
        print("no D30 results files; nothing written")
        return 1
    S.TAB.mkdir(parents=True, exist_ok=True)
    regression(res).to_csv(S.TAB / "d30_regression.csv", index=False)
    classification(res).to_csv(S.TAB / "d30_classification.csv", index=False)
    groups = per_group(res)
    groups.to_csv(S.TAB / "d30_per_group.csv", index=False)
    written = [fig_confusion(res), fig_error_by_group(groups)]
    for p in [S.PTAB / "d30_regression.tex", S.PTAB / "d30_classification.tex", *[w for w in written if w]]:
        print("wrote", p.relative_to(ROOT) if p.is_relative_to(ROOT) else p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
