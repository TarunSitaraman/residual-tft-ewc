"""Write paper/paper_single.tex: main.tex with every \\input{...} inlined.

The single file needs only references.bib and figures/ next to it. Regenerate after any
change to the paper (from the repository root)::

    python scripts/flatten_paper.py          # write
    python scripts/flatten_paper.py --check  # exit 1 if paper_single.tex is out of date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1] / "paper"
OUT = PAPER / "paper_single.tex"
INPUT = re.compile(r"^[ \t]*\\input\{([^}]+)\}[ \t]*$", re.MULTILINE)
HEADER = "% Generated by scripts/flatten_paper.py from paper/main.tex. Do not edit; edit the sources.\n"


def inline(path: Path) -> str:
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    return INPUT.sub(lambda m: inline(PAPER / (m.group(1).removesuffix(".tex") + ".tex")).rstrip("\n"), text)


def main() -> int:
    text = HEADER + inline(PAPER / "main.tex")
    assert "\\input{" not in text, "unresolved \\input"
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("paper/paper_single.tex is out of date; run python scripts/flatten_paper.py")
            return 1
        print("paper/paper_single.tex is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(PAPER.parent))
    return 0


if __name__ == "__main__":
    sys.exit(main())
