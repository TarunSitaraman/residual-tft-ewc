"""Generate the paper's result tables and copy its figures from committed results.

Every number in ``paper/tables/*.tex`` is read from a committed results file
(``results/forecasting.json`` for S1, ``results/forecasting_wheeler.json`` for
S6), and each table records the commit that produced it. The script refuses to
use a results file written from a dirty working tree.

Usage (from the repository root)::

    python scripts/make_paper_tables.py
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "tables"
FIG_OUT = ROOT / "paper" / "figures"
FILES = {"S1": ROOT / "results" / "forecasting.json", "S6": ROOT / "results" / "forecasting_wheeler.json"}
FIGURES = ("12_p1_rmse", "13_p1_rmse", "13_soh_trajectories", "13_tft_ewc_matrix", "11_ic_curves")

NAMES = {
    "persistence": "Persistence", "linear_extrapolation": "Linear extrapolation", "ridge_schedule": "Ridge, usage only",
    "ridge_F0": "Ridge, F0", "ridge_F1": "Ridge, F1", "gbm_F1": "Gradient boosting, F1",
    "finetune": "MLP fine-tuning", "replay": "MLP replay", "ewc": "MLP + EWC", "joint": "MLP joint$^\\dagger$",
    "tft_finetune": "TFT fine-tuning", "tft_ewc": "\\textbf{TFT + EWC}", "tft_ewc_F0": "TFT + EWC, F0",
    "tft_joint": "TFT joint$^\\dagger$", "mlp": "MLP", "tft": "TFT",
}
ORDER = ["persistence", "linear_extrapolation", "ridge_schedule", "ridge_F0", "ridge_F1", "gbm_F1",
         "finetune", "replay", "ewc", "joint", "tft_finetune", "tft_ewc", "tft_ewc_F0", "tft_joint", "mlp", "tft"]


def load() -> dict:
    res = {}
    for k, path in FILES.items():
        r = json.loads(path.read_text())
        if r["environment"].get("git_dirty"):
            raise SystemExit(f"{path} was written from a dirty working tree; re-run it on a clean commit")
        res[k] = r
    return res


def f(x, nd=3) -> str:
    return "--" if x is None or pd.isna(x) else f"{x:.{nd}f}"


def p_fmt(p) -> str:
    return "--" if pd.isna(p) else ("$<$0.001" if p < 0.001 else f"{p:.3f}")


def source(res, keys=("S1", "S6")) -> str:
    return "% Generated by scripts/make_paper_tables.py from " + ", ".join(
        f"{FILES[k].relative_to(ROOT)} (commit {res[k]['environment']['git_commit'][:7]})" for k in keys) + "\n"


def table_hyper(res) -> str:
    rows = []
    for k in ("S1", "S6"):
        t = res[k]["tuning"]
        rows.append(f"{k} & {t['backbone_selected']['mlp']['lr']:g} & {t['backbone_selected']['tft']['lr']:g} & "
                    f"{t['selected']['replay']['buffer_per_task']} & {t['selected']['ewc']['ewc_lambda']:g} & "
                    f"{t['selected']['tft_ewc']['ewc_lambda']:g} \\\\")
    return source(res) + r"""\begin{table}[t]
  \centering
  \caption{Hyperparameters selected on validation data only.}
  \label{tab:hyper}
  \begin{tabular}{lccccc}
    \toprule
    Data & lr MLP & lr TFT & Replay $B$ & $\lambda$ MLP & $\lambda$ TFT \\
    \midrule
""" + "\n".join("    " + r for r in rows) + r"""
    \bottomrule
  \end{tabular}
\end{table}
"""


def _p1_frame(r) -> pd.DataFrame:
    t = pd.DataFrame(r["p1_rmse"]).set_index("method")
    cl = pd.DataFrame(r["p1_cl_summary"]).set_index("method")
    return t.join(cl[["forgetting_mean", "forgetting_ci_low", "forgetting_ci_high"]], how="left")


def table_p1(res) -> str:
    a, b = _p1_frame(res["S1"]), _p1_frame(res["S6"])
    methods = [m for m in ORDER if m in a.index or m in b.index]
    lines = []
    for m in methods:
        cells = [NAMES[m]]
        for t in (a, b):
            if m in t.index:
                row = t.loc[m]
                sd = f" $\\pm$ {row['std']:.3f}" if pd.notna(row["std"]) else ""
                cells += [f"{row['mean']:.3f}{sd}", f(row["skill_vs_persistence"], 2), f(row.get("forgetting_mean"))]
            else:
                cells += ["--", "--", "--"]
        lines.append(" & ".join(cells) + " \\\\")
        if m in ("gbm_F1", "joint"):
            lines.append("\\midrule")
    return source(res) + r"""\begin{table*}[t]
  \centering
  \caption{Protocol P1 (continual stream). Final average test RMSE of SOH$(k{+}h)$ in pp (mean $\pm$ s.d.\ over 10 orders $\times$ 5 seeds for continual methods, over 5 seeds for joint training), skill relative to persistence ($1-\mathrm{RMSE}/\mathrm{RMSE}_{\mathrm{persistence}}$) and forgetting (pp). $^\dagger$Upper bound, trained on all tasks at once.}
  \label{tab:p1}
  \begin{tabular}{lccc|ccc}
    \toprule
    & \multicolumn{3}{c|}{S1: six NMC second-life cells} & \multicolumn{3}{c}{S6: 20 LFP cells, seven usage conditions} \\
    Method & RMSE & Skill & Forgetting & RMSE & Skill & Forgetting \\
    \midrule
""" + "\n".join("    " + l for l in lines) + r"""
    \bottomrule
  \end{tabular}
\end{table*}
"""


def table_horizon(res) -> str:
    keep = ["persistence", "linear_extrapolation", "gbm_F1", "finetune", "tft_finetune", "tft_ewc", "tft_joint"]
    lines = []
    for m in keep:
        cells = [NAMES[m]]
        for k in ("S1", "S6"):
            t = pd.DataFrame(res[k]["p1_rmse_by_horizon"]).set_index("method")
            cells += [f(t.loc[m, c], 2) if m in t.index else "--" for c in ("RMSE_h1", "RMSE_h2", "RMSE_h3")]
        lines.append(" & ".join(cells) + " \\\\")
    return source(res) + r"""\begin{table}[t]
  \centering
  \caption{P1 test RMSE (pp) by forecast horizon $h$ (RPTs or checks ahead).}
  \label{tab:horizon}
  \setlength{\tabcolsep}{3.5pt}
  \begin{tabular}{lccc|ccc}
    \toprule
    & \multicolumn{3}{c|}{S1} & \multicolumn{3}{c}{S6} \\
    Method & $h{=}1$ & 2 & 3 & 1 & 2 & 3 \\
    \midrule
""" + "\n".join("    " + l for l in lines) + r"""
    \bottomrule
  \end{tabular}
\end{table}
"""


def table_tests(res) -> str:
    lines = []
    for k in ("S1", "S6"):
        t = pd.DataFrame(res[k]["p1_tests_vs_tft_ewc"])
        t = t[t["metric"].isin(["final_avg_error", "forgetting"])]
        for metric, label in (("final_avg_error", "Final error"), ("forgetting", "Forgetting")):
            for _, r in t[t["metric"] == metric].iterrows():
                # compare_methods reports other - TFT+EWC; flip to TFT+EWC - other like the baseline rows.
                lines.append(f"{k} & {label} & {NAMES[r['method']]} & {-r['mean_diff']:+.3f} [{-r['ci_high']:+.3f}, {-r['ci_low']:+.3f}] & "
                             f"{p_fmt(r['p_holm'])} & {-r['rank_biserial']:+.2f} \\\\")
        b = pd.DataFrame(res[k]["p1_tft_ewc_vs_baselines"])
        for _, r in b.iterrows():
            lines.append(f"{k} & Final error & {NAMES[r['baseline']]} & {r['mean_diff']:+.3f} [{r['ci_low']:+.3f}, {r['ci_high']:+.3f}] & "
                         f"{p_fmt(r['p_holm'])} & {r['rank_biserial']:+.2f} \\\\")
        if k == "S1":
            lines.append("\\midrule")
    return source(res) + r"""\begin{table*}[t]
  \centering
  \caption{P1 paired comparisons of TFT + EWC with every other method: difference TFT + EWC $-$ other (pp; negative favours TFT + EWC) with 95\% bootstrap CI, Holm-adjusted Wilcoxon $p$ and rank-biserial effect size. Comparisons with baselines use the baseline's single value.}
  \label{tab:tests}
  \begin{tabular}{lllccc}
    \toprule
    Data & Metric & Compared with & Difference [95\% CI] & $p_{\mathrm{Holm}}$ & $r_{\mathrm{rb}}$ \\
    \midrule
""" + "\n".join("    " + l for l in lines) + r"""
    \bottomrule
  \end{tabular}
\end{table*}
"""


def table_p2(res) -> str:
    lines = []
    for k in ("S1", "S6"):
        t = pd.DataFrame(res[k]["p2_rmse"]).set_index("method")
        groups = [c for c in t.columns if c not in ("mean", "class_accuracy", "class_macro_f1")]
        order = [m for m in ORDER if m in t.index]
        for m in order:
            row = t.loc[m]
            cls = f"{f(row.get('class_accuracy'), 2)} / {f(row.get('class_macro_f1'), 2)}" if k == "S6" else "--"
            lines.append(f"{k} & {NAMES[m]} & {row['mean']:.3f} & {row[groups].min():.3f}--{row[groups].max():.3f} & {cls} \\\\")
        if k == "S1":
            lines.append("\\midrule")
    return source(res) + r"""\begin{table}[t]
  \centering
  \caption{Protocol P2 (unseen battery in S1, unseen usage condition in S6): mean test RMSE (pp) over held-out groups, range over groups, and for S6 reuse-class accuracy / macro-F1 of the forecast SOH.}
  \label{tab:p2}
  \setlength{\tabcolsep}{3pt}
  \begin{tabular}{llccc}
    \toprule
    Data & Method & RMSE & Range & Class acc./F1 \\
    \midrule
""" + "\n".join("    " + l for l in lines) + r"""
    \bottomrule
  \end{tabular}
\end{table}
"""


def main() -> int:
    res = load()
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in (("hyper", table_hyper), ("p1", table_p1), ("horizon", table_horizon), ("tests", table_tests), ("p2", table_p2)):
        (OUT / f"{name}.tex").write_text(fn(res))
    FIG_OUT.mkdir(parents=True, exist_ok=True)
    missing = []
    for fig in FIGURES:
        src = ROOT / "results" / "figures" / f"{fig}.png"
        if src.exists():
            shutil.copy2(src, FIG_OUT / f"{fig}.png")
        elif not (FIG_OUT / f"{fig}.png").exists():
            missing.append(fig)
    if missing:
        print("missing figures (run notebooks 11-13):", missing, file=sys.stderr)
    print("tables:", sorted(p.name for p in OUT.glob("*.tex")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
