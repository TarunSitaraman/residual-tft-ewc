"""Generate the result tables from committed results files.

Every number is read from a committed results file (``results/forecasting.json``
for S1, ``results/forecasting_wheeler.json`` for S6). The script refuses to use
a results file written from a dirty working tree. It writes

- ``results/tables/*.csv``: machine-readable tables for the manuscript;
- the generated block of ``docs/RESULTS.md`` (between the GENERATED markers);
- ``paper/tables/*.tex``: the same tables typeset for LaTeX;
- ``paper/figures/*.png``: copies of the notebook figures used by the results section.

The LaTeX tables and ``docs/RESULTS.md`` record the commit of the results files they were built from.

Usage (from the repository root)::

    python scripts/make_results_tables.py
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "tables"
CSV_OUT = ROOT / "results" / "tables"
RESULTS_MD = ROOT / "docs" / "RESULTS.md"
BEGIN, END = "<!-- BEGIN GENERATED TABLES -->", "<!-- END GENERATED TABLES -->"
FIG_OUT = ROOT / "paper" / "figures"
FILES = {"S1": ROOT / "results" / "forecasting.json", "S6": ROOT / "results" / "forecasting_wheeler.json"}
FIGURES = ("12_p1_rmse", "13_p1_rmse", "13_soh_trajectories", "13_tft_ewc_matrix", "11_ic_curves")

NAMES = {
    "persistence": "Persistence", "linear_extrapolation": "Linear extrapolation", "ridge_schedule": "Ridge, usage only",
    "ridge_F0": "Ridge, F0", "ridge_F1": "Ridge, F1", "gbm_F1": "Gradient boosting, F1",
    "finetune": "MLP fine-tuning", "replay": "MLP replay", "ewc": "MLP + EWC", "joint": "MLP joint$^\\dagger$",
    "tft_finetune": "TFT fine-tuning", "tft_ewc": "\\textbf{TFT + EWC}", "tft_ewc_F0": "TFT + EWC, F0",
    "tft_joint": "TFT joint$^\\dagger$", "mlp": "MLP", "tft": "TFT",
}
ORDER = ["persistence", "linear_extrapolation", "ridge_schedule", "ridge_F0", "ridge_F1", "gbm_F1",
         "finetune", "replay", "ewc", "joint", "tft_finetune", "tft_ewc", "tft_ewc_F0", "tft_joint", "mlp", "tft"]


def load() -> dict:
    res = {}
    for k, path in FILES.items():
        r = json.loads(path.read_text())
        if r["environment"].get("git_dirty"):
            raise SystemExit(f"{path} was written from a dirty working tree; re-run it on a clean commit")
        res[k] = r
    return res


def f(x, nd=3) -> str:
    return "--" if x is None or pd.isna(x) else f"{x:.{nd}f}"


def p_fmt(p) -> str:
    return "--" if pd.isna(p) else ("$<$0.001" if p < 0.001 else f"{p:.3f}")


def source(res, keys=("S1", "S6")) -> str:
    return "% Generated by scripts/make_results_tables.py from " + ", ".join(
        f"{FILES[k].relative_to(ROOT)} (commit {res[k]['environment']['git_commit'][:7]})" for k in keys) + "\n"


def table_hyper(res) -> str:
    rows = []
    for k in ("S1", "S6"):
        t = res[k]["tuning"]
        rows.append(f"{k} & {t['backbone_selected']['mlp']['lr']:g} & {t['backbone_selected']['tft']['lr']:g} & "
                    f"{t['selected']['replay']['buffer_per_task']} & {t['selected']['ewc']['ewc_lambda']:g} & "
                    f"{t['selected']['tft_ewc']['ewc_lambda']:g} \\\\")
    return source(res) + r"""\begin{table}[t]
  \centering
  \caption{Hyperparameters selected on validation data only.}
  \label{tab:hyper}
  \begin{tabular}{lccccc}
    \toprule
    Data & lr MLP & lr TFT & Replay $B$ & $\lambda$ MLP & $\lambda$ TFT \\
    \midrule
""" + "\n".join("    " + r for r in rows) + r"""
    \bottomrule
  \end{tabular}
\end{table}
"""


def _p1_frame(r) -> pd.DataFrame:
    t = pd.DataFrame(r["p1_rmse"]).set_index("method")
    cl = pd.DataFrame(r["p1_cl_summary"]).set_index("method")
    return t.join(cl[["forgetting_mean", "forgetting_ci_low", "forgetting_ci_high"]], how="left")


def table_p1(res) -> str:
    a, b = _p1_frame(res["S1"]), _p1_frame(res["S6"])
    methods = [m for m in ORDER if m in a.index or m in b.index]
    lines = []
    for m in methods:
        cells = [NAMES[m]]
        for t in (a, b):
            if m in t.index:
                row = t.loc[m]
                sd = f" $\\pm$ {row['std']:.3f}" if pd.notna(row["std"]) else ""
                cells += [f"{row['mean']:.3f}{sd}", f(row["skill_vs_persistence"], 2), f(row.get("forgetting_mean"))]
            else:
                cells += ["--", "--", "--"]
        lines.append(" & ".join(cells) + " \\\\")
        if m in ("gbm_F1", "joint"):
            lines.append("\\midrule")
    return source(res) + r"""\begin{table*}[t]
  \centering
  \caption{Protocol P1 (continual stream). Final average test RMSE of SOH$(k{+}h)$ in pp (mean $\pm$ s.d.\ over 10 orders $\times$ 5 seeds for continual methods, over 5 seeds for joint training), skill relative to persistence ($1-\mathrm{RMSE}/\mathrm{RMSE}_{\mathrm{persistence}}$) and forgetting (pp). $^\dagger$Upper bound, trained on all tasks at once.}
  \label{tab:p1}
  \begin{tabular}{lccc|ccc}
    \toprule
    & \multicolumn{3}{c|}{S1: six NMC second-life cells} & \multicolumn{3}{c}{S6: 20 LFP cells, seven usage conditions} \\
    Method & RMSE & Skill & Forgetting & RMSE & Skill & Forgetting \\
    \midrule
""" + "\n".join("    " + l for l in lines) + r"""
    \bottomrule
  \end{tabular}
\end{table*}
"""


def table_horizon(res) -> str:
    keep = ["persistence", "linear_extrapolation", "gbm_F1", "finetune", "tft_finetune", "tft_ewc", "tft_joint"]
    lines = []
    for m in keep:
        cells = [NAMES[m]]
        for k in ("S1", "S6"):
            t = pd.DataFrame(res[k]["p1_rmse_by_horizon"]).set_index("method")
            cells += [f(t.loc[m, c], 2) if m in t.index else "--" for c in ("RMSE_h1", "RMSE_h2", "RMSE_h3")]
        lines.append(" & ".join(cells) + " \\\\")
    return source(res) + r"""\begin{table}[t]
  \centering
  \caption{P1 test RMSE (pp) by forecast horizon $h$ (RPTs or checks ahead).}
  \label{tab:horizon}
  \setlength{\tabcolsep}{3.5pt}
  \begin{tabular}{lccc|ccc}
    \toprule
    & \multicolumn{3}{c|}{S1} & \multicolumn{3}{c}{S6} \\
    Method & $h{=}1$ & 2 & 3 & 1 & 2 & 3 \\
    \midrule
""" + "\n".join("    " + l for l in lines) + r"""
    \bottomrule
  \end{tabular}
\end{table}
"""


def table_tests(res) -> str:
    lines = []
    for k in ("S1", "S6"):
        t = pd.DataFrame(res[k]["p1_tests_vs_tft_ewc"])
        t = t[t["metric"].isin(["final_avg_error", "forgetting"])]
        for metric, label in (("final_avg_error", "Final error"), ("forgetting", "Forgetting")):
            for _, r in t[t["metric"] == metric].iterrows():
                # compare_methods reports other - TFT+EWC; flip to TFT+EWC - other like the baseline rows.
                lines.append(f"{k} & {label} & {NAMES[r['method']]} & {-r['mean_diff']:+.3f} [{-r['ci_high']:+.3f}, {-r['ci_low']:+.3f}] & "
                             f"{p_fmt(r['p_holm'])} & {-r['rank_biserial']:+.2f} \\\\")
        b = pd.DataFrame(res[k]["p1_tft_ewc_vs_baselines"])
        for _, r in b.iterrows():
            lines.append(f"{k} & Final error & {NAMES[r['baseline']]} & {r['mean_diff']:+.3f} [{r['ci_low']:+.3f}, {r['ci_high']:+.3f}] & "
                         f"{p_fmt(r['p_holm'])} & {r['rank_biserial']:+.2f} \\\\")
        if k == "S1":
            lines.append("\\midrule")
    return source(res) + r"""\begin{table*}[t]
  \centering
  \caption{P1 paired comparisons of TFT + EWC with every other method: difference TFT + EWC $-$ other (pp; negative favours TFT + EWC) with 95\% bootstrap CI, Holm-adjusted Wilcoxon $p$ and rank-biserial effect size. Comparisons with baselines use the baseline's single value.}
  \label{tab:tests}
  \begin{tabular}{lllccc}
    \toprule
    Data & Metric & Compared with & Difference [95\% CI] & $p_{\mathrm{Holm}}$ & $r_{\mathrm{rb}}$ \\
    \midrule
""" + "\n".join("    " + l for l in lines) + r"""
    \bottomrule
  \end{tabular}
\end{table*}
"""


def table_p2(res) -> str:
    lines = []
    for k in ("S1", "S6"):
        t = pd.DataFrame(res[k]["p2_rmse"]).set_index("method")
        groups = [c for c in t.columns if c not in ("mean", "class_accuracy", "class_macro_f1")]
        order = [m for m in ORDER if m in t.index]
        for m in order:
            row = t.loc[m]
            cls = f"{f(row.get('class_accuracy'), 2)} / {f(row.get('class_macro_f1'), 2)}" if k == "S6" else "--"
            lines.append(f"{k} & {NAMES[m]} & {row['mean']:.3f} & {row[groups].min():.3f}--{row[groups].max():.3f} & {cls} \\\\")
        if k == "S1":
            lines.append("\\midrule")
    return source(res) + r"""\begin{table}[t]
  \centering
  \caption{Protocol P2 (unseen battery in S1, unseen usage condition in S6): mean test RMSE (pp) over held-out groups, range over groups, and for S6 reuse-class accuracy / macro-F1 of the forecast SOH.}
  \label{tab:p2}
  \setlength{\tabcolsep}{3pt}
  \begin{tabular}{llccc}
    \toprule
    Data & Method & RMSE & Range & Class acc./F1 \\
    \midrule
""" + "\n".join("    " + l for l in lines) + r"""
    \bottomrule
  \end{tabular}
\end{table}
"""


# --- Plain tables (CSV and Markdown) -------------------------------------------------

def plain(m: str) -> str:
    return NAMES[m].replace("\\textbf{", "").replace("}", "").replace("$^\\dagger$", " (upper bound)")


def frame_hyper(res) -> pd.DataFrame:
    rows = []
    for k in ("S1", "S6"):
        t = res[k]["tuning"]
        rows.append({"dataset": k, "lr_mlp": t["backbone_selected"]["mlp"]["lr"], "lr_tft": t["backbone_selected"]["tft"]["lr"],
                     "replay_buffer_per_task": t["selected"]["replay"]["buffer_per_task"],
                     "ewc_lambda_mlp": t["selected"]["ewc"]["ewc_lambda"], "ewc_lambda_tft": t["selected"]["tft_ewc"]["ewc_lambda"]})
    return pd.DataFrame(rows)


def frame_p1(res) -> pd.DataFrame:
    rows = []
    for k in ("S1", "S6"):
        t = _p1_frame(res[k])
        for m in [m for m in ORDER if m in t.index]:
            r = t.loc[m]
            rows.append({"dataset": k, "method": m, "name": plain(m), "rmse_pp_mean": r["mean"], "rmse_pp_sd": r["std"], "n_runs": r["size"],
                         "skill_vs_persistence": r["skill_vs_persistence"], "forgetting_pp_mean": r.get("forgetting_mean"),
                         "forgetting_ci_low": r.get("forgetting_ci_low"), "forgetting_ci_high": r.get("forgetting_ci_high")})
    return pd.DataFrame(rows)


def frame_horizon(res) -> pd.DataFrame:
    rows = []
    for k in ("S1", "S6"):
        t = pd.DataFrame(res[k]["p1_rmse_by_horizon"]).set_index("method")
        for m in [m for m in ORDER if m in t.index]:
            rows.append({"dataset": k, "method": m, "name": plain(m),
                         **{f"rmse_pp_h{h}": t.loc[m, f"RMSE_h{h}"] for h in (1, 2, 3)}})
    return pd.DataFrame(rows)


def frame_tests(res) -> pd.DataFrame:
    """Paired P1 comparisons, all as TFT + EWC minus the other method (negative favours TFT + EWC)."""
    rows = []
    for k in ("S1", "S6"):
        t = pd.DataFrame(res[k]["p1_tests_vs_tft_ewc"])
        for _, r in t[t["metric"].isin(["final_avg_error", "forgetting"])].iterrows():
            rows.append({"dataset": k, "metric": r["metric"], "compared_with": r["method"], "diff_pp": -r["mean_diff"],
                         "ci_low": -r["ci_high"], "ci_high": -r["ci_low"], "n": r["n"], "p_holm": r["p_holm"],
                         "rank_biserial": -r["rank_biserial"]})
        for _, r in pd.DataFrame(res[k]["p1_tft_ewc_vs_baselines"]).iterrows():
            rows.append({"dataset": k, "metric": "final_avg_error", "compared_with": r["baseline"], "diff_pp": r["mean_diff"],
                         "ci_low": r["ci_low"], "ci_high": r["ci_high"], "n": r["n"], "p_holm": r["p_holm"],
                         "rank_biserial": r["rank_biserial"]})
    return pd.DataFrame(rows)


def frame_p2(res) -> pd.DataFrame:
    rows = []
    for k in ("S1", "S6"):
        t = pd.DataFrame(res[k]["p2_rmse"]).set_index("method")
        groups = [c for c in t.columns if c not in ("mean", "class_accuracy", "class_macro_f1")]
        for m in [m for m in ORDER if m in t.index]:
            r = t.loc[m]
            rows.append({"dataset": k, "method": m, "name": plain(m), "rmse_pp_mean": r["mean"], "rmse_pp_min": r[groups].min(),
                         "rmse_pp_max": r[groups].max(), "hardest_group": r[groups].astype(float).idxmax(),
                         "class_accuracy": r.get("class_accuracy", float("nan")) if k == "S6" else float("nan"),
                         "class_macro_f1": r.get("class_macro_f1", float("nan")) if k == "S6" else float("nan")})
    return pd.DataFrame(rows)


INT_COLS = {"n", "n_runs", "replay_buffer_per_task"}


def markdown(df: pd.DataFrame, nd=3) -> str:
    def cell(col, x):
        if not isinstance(x, float):
            return str(x)
        if pd.isna(x):
            return "--"
        if col in INT_COLS:
            return f"{x:.0f}"
        if col == "p_holm":
            return "<0.001" if x < 0.001 else f"{x:.3f}"
        if col.startswith("lr_") or col.startswith("ewc_lambda"):
            return f"{x:g}"
        return f"{x:.{nd}f}"
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(cell(c, v) for c, v in zip(cols, row)) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


TITLES = {
    "hyper": "Hyperparameters selected on validation data only",
    "p1": "P1 (continual stream): final average test RMSE of SOH(k+h) in pp, mean and s.d. over runs; skill = 1 - RMSE/RMSE_persistence; forgetting in pp",
    "horizon": "P1 test RMSE (pp) by horizon h (RPTs or checks ahead)",
    "tests": "P1 paired comparisons: TFT + EWC minus the other method (pp; negative favours TFT + EWC), 95 % bootstrap CI, Holm-adjusted Wilcoxon p, rank-biserial r",
    "p2": "P2 (leave one group out: unseen cell in S1, unseen usage condition in S6): test RMSE (pp), range over held-out groups, S6 reuse-class accuracy / macro-F1",
}


def write_plain(res) -> None:
    CSV_OUT.mkdir(parents=True, exist_ok=True)
    frames = {"hyper": frame_hyper(res), "p1": frame_p1(res), "horizon": frame_horizon(res), "tests": frame_tests(res), "p2": frame_p2(res)}
    stamp = ", ".join(f"`{FILES[k].relative_to(ROOT)}` (commit `{res[k]['environment']['git_commit'][:7]}`)" for k in ("S1", "S6"))
    blocks = [f"_Generated by `scripts/make_results_tables.py` from {stamp}. Do not edit by hand._"]
    for name, df in frames.items():
        df.to_csv(CSV_OUT / f"{name}.csv", index=False)
        shown = df.drop(columns=[c for c in ("method",) if c in df.columns and "name" in df.columns])
        blocks.append(f"### Table `{name}`: {TITLES[name]}\n\nCSV: `results/tables/{name}.csv`\n\n{markdown(shown)}")
    text = RESULTS_MD.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{RESULTS_MD} has no generated-table markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    RESULTS_MD.write_text(head + BEGIN + "\n\n" + "\n\n".join(blocks) + "\n\n" + END + tail)


def main() -> int:
    res = load()
    write_plain(res)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in (("hyper", table_hyper), ("p1", table_p1), ("horizon", table_horizon), ("tests", table_tests), ("p2", table_p2)):
        (OUT / f"{name}.tex").write_text(fn(res))
    FIG_OUT.mkdir(parents=True, exist_ok=True)
    missing = []
    for fig in FIGURES:
        src = ROOT / "results" / "figures" / f"{fig}.png"
        if src.exists():
            shutil.copy2(src, FIG_OUT / f"{fig}.png")
        elif not (FIG_OUT / f"{fig}.png").exists():
            missing.append(fig)
    if missing:
        print("missing figures (run notebooks 11-13):", missing, file=sys.stderr)
    print("tables:", sorted(p.name for p in CSV_OUT.glob("*.csv")), "+ LaTeX and docs/RESULTS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
